"""Petite police pixel 3×5 (majuscules, chiffres) pour écrans et signalétique."""
import numpy as np

_G = {
    "A": "111101111101101", "B": "110101110101110", "C": "111100100100111", "D": "110101101101110",
    "E": "111100110100111", "F": "111100110100100", "G": "111100101101111", "H": "101101111101101",
    "I": "111010010010111", "J": "001001001101111", "K": "101101110101101", "L": "100100100100111",
    "M": "101111111101101", "N": "110101101101101", "O": "111101101101111", "P": "111101111100100",
    "Q": "111101101111001", "R": "110101110101101", "S": "111100111001111", "T": "111010010010010",
    "U": "101101101101111", "V": "101101101101010", "W": "101101111111101", "X": "101101010101101",
    "Y": "101101010010010", "Z": "111001010100111", "0": "111101101101111", "1": "010110010010111",
    "2": "111001111100111", "3": "111001111001111", "4": "101101111001001", "5": "111100111001111",
    "6": "111100111101111", "7": "111001001010010", "8": "111101111101111", "9": "111101111001111",
    " ": "000000000000000", ".": "000000000000010", "!": "010010010000010", ":": "000010000010000",
    "-": "000000111000000", "+": "000010111010000", "%": "101001010100101", "€": "011100110100011",
    "/": "001001010100100", "?": "111001011000010", "'": "010010000000000",
}


def glyph(ch):
    bits = _G.get(ch.upper(), _G["?"])
    return np.array([int(b) for b in bits], dtype=bool).reshape(5, 3)


def text_mask(s, spacing=1):
    if not s:
        return np.zeros((5, 0), dtype=bool)
    cols = []
    for i, ch in enumerate(s):
        if i:
            cols.append(np.zeros((5, spacing), dtype=bool))
        cols.append(glyph(ch))
    return np.concatenate(cols, axis=1)


def draw_text(a, s, x, y, color, spacing=1, shadow=None):
    m = text_mask(s, spacing)
    h, w = m.shape
    if shadow is not None:
        sub = a[y + 1 : y + 1 + h, x + 1 : x + 1 + w]
        mm = m[: sub.shape[0], : sub.shape[1]]
        sub[mm] = shadow
    sub = a[y : y + h, x : x + w]
    mm = m[: sub.shape[0], : sub.shape[1]]
    sub[mm] = color
    return w
